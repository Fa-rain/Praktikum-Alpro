# Program untuk mengecek posisi bilangan bulat pada deret bilangan
# apakah negatif, positif, atau nol

print("Program untuk mengecek posisi bilangan bulat pada deret bilangan")
angka = int(input("Masukkan angka : "))

if angka > 0 :
    print("Positif")
elif angka < 0 :
    print("Negatif")
else :
    print("Nol")
